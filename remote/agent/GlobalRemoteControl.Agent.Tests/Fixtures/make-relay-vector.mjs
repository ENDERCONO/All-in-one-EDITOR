// Fixed test vector for the encrypted relay (PROTOCOL.md section 7), produced by the BROWSER code itself:
// remote/web/protocol.js (deriveRelayKeys + RelayCodec). The C# RelayCryptoVectorTests must reproduce these bytes
// exactly and decrypt them.
//
//   node remote/agent/GlobalRemoteControl.Agent.Tests/Fixtures/make-relay-vector.mjs [out.json]
//
// Without an argument it rewrites relay-vector.json next to this script. Everything is deterministic: fixed ECDH
// private scalars, sessionId, counters and payloads (AES-GCM with a counter nonce has no randomness).
import { createECDH, webcrypto } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

if (!globalThis.crypto) globalThis.crypto = webcrypto;
const here = dirname(fileURLToPath(import.meta.url));
const P = await import(pathToFileURL(resolve(here, '../../../web/protocol.js')).href);
const subtle = globalThis.crypto.subtle;

const hex = (u) => Buffer.from(u).toString('hex');
const b64u = (u) => Buffer.from(u).toString('base64url');

/** A P-256 key from a fixed private scalar; returns the WebCrypto ECDH private key and the raw parts. */
async function fixedKey(dHex) {
  const ecdh = createECDH('prime256v1');
  ecdh.setPrivateKey(Buffer.from(dHex, 'hex'));
  const pub = ecdh.getPublicKey(); // 04 | x | y
  const x = pub.subarray(1, 33), y = pub.subarray(33, 65), d = Buffer.from(dHex, 'hex');
  const jwk = { kty: 'EC', crv: 'P-256', d: b64u(d), x: b64u(x), y: b64u(y), ext: true };
  const privateKey = await subtle.importKey('jwk', jwk, { name: 'ECDH', namedCurve: 'P-256' }, false, ['deriveBits']);
  const pubKey = await subtle.importKey('jwk', { kty: 'EC', crv: 'P-256', x: jwk.x, y: jwk.y, ext: true },
    { name: 'ECDH', namedCurve: 'P-256' }, true, []);
  const spki = P.bytesToB64(new Uint8Array(await subtle.exportKey('spki', pubKey)));
  return { privateKey, d: hex(d), x: hex(x), y: hex(y), spki };
}

const sessionId = 'AbCdEfGhIjKlMnOpQrSt_-';
const controller = await fixedKey('c0ffee00112233445566778899aabbccddeeff00112233445566778899aabb01');
const device = await fixedKey('d00dfeed8899aabbccddeeff00112233445566778899aabbccddeeff00112202');

// Independent intermediates (plain WebCrypto, not protocol.js) so a mismatch can be localised.
const peerPub = await subtle.importKey('spki', P.b64ToBytes(device.spki), { name: 'ECDH', namedCurve: 'P-256' }, false, []);
const z = new Uint8Array(await subtle.deriveBits({ name: 'ECDH', public: peerPub }, controller.privateKey, 256));
const hk = await subtle.importKey('raw', z, 'HKDF', false, ['deriveBits']);
const hkdf = async (info) => hex(new Uint8Array(await subtle.deriveBits(
  { name: 'HKDF', hash: 'SHA-256', salt: new TextEncoder().encode(sessionId), info: new TextEncoder().encode(info) }, hk, 256)));

// The browser's own codecs, both roles.
const ctlKeys = await P.deriveRelayKeys(controller.privateKey, device.spki, sessionId, 'controller');
const devKeys = await P.deriveRelayKeys(device.privateKey, controller.spki, sessionId, 'device');
const ctl = new P.RelayCodec(sessionId, ctlKeys.send, ctlKeys.recv);
const dev = new P.RelayCodec(sessionId, devKeys.send, devKeys.recv);

const pattern = (n, seed) => Uint8Array.from({ length: n }, (_, i) => (i * 31 + seed) & 0xff);
const msgs = {
  c2d: [
    [0, new TextEncoder().encode('{"t":"mouse-move","x":0.25,"y":0.75}')],
    [3, pattern(1000, 7)],
    [0, new Uint8Array(0)],           // empty payload (plaintext = just the channel byte)
    [3, pattern(16000, 3)],           // a full-size data-channel chunk
  ],
  d2c: [
    [0, new TextEncoder().encode('{"t":"hello","mode":"control"}')],
    [1, pattern(64, 1)],
    [2, pattern(960, 9)],
  ],
};
const frames = [];
for (const [dir, codec] of [['c2d', ctl], ['d2c', dev]]) {
  for (const [channel, payload] of msgs[dir]) {
    const f = await codec.encrypt(channel, payload);
    frames.push({ direction: dir, counter: Number(codec.txCounter), channel, payload: hex(payload), frame: hex(f) });
  }
}
// sanity: the opposite end decrypts them
for (const fr of frames) {
  const r = await (fr.direction === 'c2d' ? dev : ctl).decrypt(Buffer.from(fr.frame, 'hex'));
  if (!r || r.channel !== fr.channel || hex(r.payload) !== fr.payload) throw new Error('self-check failed');
}

const out = {
  note: 'Generated by make-relay-vector.mjs from remote/web/protocol.js. Do not edit by hand.',
  sessionId,
  controller: { d: controller.d, x: controller.x, y: controller.y, spki: controller.spki },
  device: { d: device.d, x: device.x, y: device.y, spki: device.spki },
  z: hex(z),
  keyC2D: await hkdf('grc-relay c2d'),
  keyD2C: await hkdf('grc-relay d2c'),
  frames,
};
const file = process.argv[2] ? resolve(process.argv[2]) : join(here, 'relay-vector.json');
writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
console.log(file);
